/**
 * Regenerates web/src/lib/api.gen.ts, the API's response types for the web app, from the server's schemas
 * (src/contract.ts, gathered from each feature's schemas.ts). Run after changing one:  npm run api:types
 * CI fails if the file is out of date.
 */

import { writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

import { compile } from "json-schema-to-typescript";
import { z } from "zod";

import { schemas } from "../src/contract.js";

const OUT = join(dirname(fileURLToPath(import.meta.url)), "..", "..", "web", "src", "lib", "api.gen.ts");

// Registered schemas become named types that refer to each other, rather than copies inlined everywhere.
const registry = z.registry<{ id: string }>();
for (const [name, schema] of Object.entries(schemas)) registry.add(schema, { id: name });
const json = z.toJSONSchema(registry, { uri: (id) => `#/$defs/${id}`, unrepresentable: "any" });

const defs = Object.fromEntries(Object.entries(json.schemas).map(([name, s]) => {
  const { $schema: _, ...rest } = s as Record<string, unknown>;
  return [name, { ...rest, title: name }];
}));
const root = { title: "ApiTypes", type: "object", additionalProperties: false, $defs: defs,
  properties: Object.fromEntries(Object.keys(defs).map((n) => [n, { $ref: `#/$defs/${n}` }])) };

let ts = await compile(root as never, "ApiTypes", {
  bannerComment: "", additionalProperties: false, declareExternallyReferenced: true, unreachableDefinitions: true,
  format: true, strictIndexSignatures: true, style: { printWidth: 120 },
});
// The wrapper only exists to reach every definition.
ts = ts.replace(/export interface ApiTypes \{[\s\S]*?\n\}\n/, "")
  .replace(/\/\*\*\n \* This interface was referenced by[\s\S]*?\*\/\n/g, "");

writeFileSync(OUT, `// Generated by \`npm run api:types\` (server/scripts/api-types.ts) from the server's response schemas. Don't edit.\n\n${ts.trim()}\n`);
console.log(`wrote ${Object.keys(defs).length} types to web/src/lib/api.gen.ts`);
