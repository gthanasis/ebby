-- A payment linked to a fixed cost by hand: a transfer to a landlord or a card charge without a merchant name,
-- which the cost's payees can't match. Kept apart from commitment_id, which is rebuilt from the payees each time.
ALTER TABLE transactions ADD COLUMN commitment_pinned bigint REFERENCES commitments(id) ON DELETE SET NULL;

-- What the assistant remembers about someone's payments, one line each, in their words: read when it sorts and
-- when it chats.
CREATE TABLE assistant_memory (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  text text NOT NULL,
  source text NOT NULL DEFAULT 'you',   -- 'you' (typed in Settings), 'payment' (from a payment), 'chat'
  service text,                         -- the payee it came from, when it came from a payment
  created_at text NOT NULL,
  used integer NOT NULL DEFAULT 0       -- times a guess leaned on it
);
CREATE INDEX assistant_memory_user ON assistant_memory(user_id);
ALTER TABLE assistant_memory ENABLE ROW LEVEL SECURITY;
ALTER TABLE assistant_memory FORCE ROW LEVEL SECURITY;
CREATE POLICY own_rows ON assistant_memory USING (user_id = app_user()) WITH CHECK (user_id = app_user());
