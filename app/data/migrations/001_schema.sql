-- The whole schema, one database for everyone. Each person's rows carry user_id, and row-level
-- security shows a connection only the rows of the user it set (app.user_id, see db.connect).
-- The app runs as a role that doesn't own these tables, so the policies always apply to it.

CREATE TABLE users (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  email text UNIQUE NOT NULL,           -- lowercased; this table is the allow list
  name text,
  picture text,
  is_admin boolean NOT NULL DEFAULT false,
  status text NOT NULL DEFAULT 'invited',   -- invited / active / disabled
  ai_budget_usd double precision NOT NULL DEFAULT 2,  -- a month on the owner's key; ignored with their own
  created_at timestamptz NOT NULL DEFAULT now(),
  last_login_at timestamptz
);

CREATE TABLE sessions (
  token_hash bytea PRIMARY KEY,         -- sha256 of the cookie; the cookie itself is never stored
  user_id bigint NOT NULL REFERENCES users(id) ON DELETE CASCADE,
  created_at timestamptz NOT NULL DEFAULT now(),
  expires_at timestamptz NOT NULL,
  extended_at timestamptz NOT NULL DEFAULT now(),
  user_agent text
);
CREATE INDEX sessions_user ON sessions(user_id);

-- Who the current transaction is acting for. NULLIF: once a pooled connection has set it,
-- the setting reads '' rather than missing, and ''::bigint would throw.
CREATE FUNCTION app_user() RETURNS bigint LANGUAGE sql STABLE
  AS $$ SELECT NULLIF(current_setting('app.user_id', true), '')::bigint $$;

CREATE TABLE accounts (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id text NOT NULL,                     -- Enable Banking identification_hash: stable across re-authorisations
  uid text,                             -- session-specific account id used for API calls
  name text NOT NULL,
  is_card integer NOT NULL,
  last4 text,
  balance double precision,
  balance_at text,
  synced_at text,
  bank text,
  PRIMARY KEY (user_id, id)
);

CREATE TABLE transactions (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id text NOT NULL,
  account text NOT NULL,
  date text NOT NULL,
  amount double precision NOT NULL,     -- signed: negative is money out
  currency text NOT NULL,
  status text NOT NULL,
  description text NOT NULL,
  merchant text NOT NULL,
  mcc text,
  category text NOT NULL,
  raw text NOT NULL,
  commitment_id bigint,                 -- set on rows that belong to a commitment (see insights)
  duplicate_of text,                    -- a debit-card row whose current-account copy is the one that counts
  PRIMARY KEY (user_id, id)
);
CREATE INDEX transactions_date ON transactions(user_id, date);

CREATE TABLE rules (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  merchant text NOT NULL,
  category text NOT NULL,
  PRIMARY KEY (user_id, merchant)
);

CREATE TABLE connections (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  bank text NOT NULL,
  session_id text,
  valid_until text,
  auth_state text,
  backfill integer NOT NULL DEFAULT 0,
  last_sync text,
  last_error text,                      -- JSON: {at, code, message, reconnect}
  PRIMARY KEY (user_id, bank)
);

CREATE TABLE goals (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  price double precision NOT NULL,
  saved double precision NOT NULL DEFAULT 0,
  target_date text NOT NULL,
  created_at text NOT NULL,
  kind text NOT NULL DEFAULT 'buy'      -- buy / save
);

CREATE TABLE commitments (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  kind text NOT NULL DEFAULT 'chosen',  -- 'fixed' (rent, bills) or 'chosen' (a meal plan, a subscription)
  monthly_limit double precision NOT NULL,
  note text NOT NULL DEFAULT '',        -- why it's worth it, in your words
  services text NOT NULL DEFAULT '[]',  -- JSON list of service names (insights.service_name) it covers
  off_bank double precision NOT NULL DEFAULT 0,  -- paid outside the linked accounts: counted, never seen
  created_at text NOT NULL,
  every_months integer NOT NULL DEFAULT 1,  -- paid every 1, 3, 6 or 12 months
  amount double precision,              -- each time; monthly_limit stays the monthly share
  next_date text
);

CREATE TABLE assistant_messages (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation integer NOT NULL,
  role text NOT NULL,                   -- user / assistant, exactly as sent to the API
  content text NOT NULL,                -- JSON content blocks, replayed unchanged (thinking blocks included)
  created_at text NOT NULL
);

CREATE TABLE assistant_actions (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  conversation integer NOT NULL,
  kind text NOT NULL,
  params text NOT NULL,                 -- JSON
  summary text NOT NULL,
  status text NOT NULL DEFAULT 'pending',  -- pending / done / cancelled
  created_at text NOT NULL
);

CREATE TABLE wishlist (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  price double precision NOT NULL,
  created_at text NOT NULL,             -- the 48 hours count from here
  reminded integer NOT NULL DEFAULT 0,
  decision text,                        -- bought / skipped / goal, once decided
  decided_at text
);

CREATE TABLE habit_rules (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  type text NOT NULL,                   -- fewer / spend_less / nospend / wait (see habits.py)
  category text,                        -- what fewer / spend_less / wait count; none for nospend
  target double precision NOT NULL,     -- times a week, euros a week, days a week, or the euro threshold for wait
  baseline double precision NOT NULL DEFAULT 0,  -- euros a week on the category before the habit
  goal_id bigint,                       -- the goal its savings go towards, if any
  created_at text NOT NULL
);

CREATE TABLE yearly_costs (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  name text NOT NULL,
  yearly_amount double precision NOT NULL,
  due_month integer NOT NULL,           -- 1-12
  created_at text NOT NULL
);

CREATE TABLE push_subscriptions (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  endpoint text NOT NULL,
  subscription text NOT NULL,           -- JSON from PushManager.subscribe()
  created_at text NOT NULL,
  PRIMARY KEY (user_id, endpoint)
);

CREATE TABLE meta (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  key text NOT NULL,
  value text,
  PRIMARY KEY (user_id, key)
);

-- Uploaded Enable Banking keys and Anthropic keys, encrypted by app/vault.py.
CREATE TABLE credentials (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  kind text NOT NULL,                   -- enable_banking / anthropic
  key_id text NOT NULL,                 -- which master key sealed it, for rotation
  nonce bytea NOT NULL,
  ciphertext bytea NOT NULL,
  public_info jsonb NOT NULL,           -- app_id + fingerprint, or "key ending …a1b2"; safe to show
  verified_at timestamptz,
  PRIMARY KEY (user_id, kind)
);

CREATE TABLE ai_usage (
  user_id bigint NOT NULL DEFAULT app_user() REFERENCES users(id) ON DELETE CASCADE,
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  at timestamptz NOT NULL DEFAULT now(),
  feature text NOT NULL,                -- assistant / weekly_read / explain / sorter
  model text NOT NULL,
  input integer NOT NULL DEFAULT 0,
  cache_read integer NOT NULL DEFAULT 0,
  cache_write integer NOT NULL DEFAULT 0,
  output integer NOT NULL DEFAULT 0,
  cost_usd double precision NOT NULL,
  own_key boolean NOT NULL
);
CREATE INDEX ai_usage_month ON ai_usage(user_id, at);

DO $$
DECLARE t text;
BEGIN
  FOREACH t IN ARRAY ARRAY['accounts', 'transactions', 'rules', 'connections', 'goals', 'commitments',
      'assistant_messages', 'assistant_actions', 'wishlist', 'habit_rules', 'yearly_costs', 'push_subscriptions', 'meta',
      'credentials', 'ai_usage'] LOOP
    EXECUTE format('ALTER TABLE %I ENABLE ROW LEVEL SECURITY', t);
    EXECUTE format('ALTER TABLE %I FORCE ROW LEVEL SECURITY', t);
    EXECUTE format('CREATE POLICY own_rows ON %I USING (user_id = app_user()) WITH CHECK (user_id = app_user())', t);
  END LOOP;
END $$;

-- The admin's People screen: what each person spent on AI this month. Totals only, never their data.
-- SECURITY DEFINER runs it as the owner, which (a superuser in the postgres image) isn't held back by the policies.
CREATE FUNCTION admin_ai_usage(since timestamptz) RETURNS TABLE(user_id bigint, cost_usd double precision)
  LANGUAGE sql STABLE SECURITY DEFINER SET search_path = public
  AS $$ SELECT user_id, COALESCE(SUM(cost_usd), 0) FROM ai_usage WHERE at >= since GROUP BY user_id $$;
